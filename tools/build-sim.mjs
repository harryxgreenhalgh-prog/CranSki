// Bundles the deterministic simulation (src/sim/verify.js and everything it
// imports, including the parts of Three.js it uses) into one file for the
// submit-run Edge Function:  npm run build:sim
import { build } from 'vite';
import { readFileSync, writeFileSync } from 'node:fs';
import { simSourceHash } from './sim-hash.mjs';

const OUT_DIR = 'supabase/functions/submit-run';
const OUT = `${OUT_DIR}/sim.js`;

await build({
  configFile: false,
  logLevel: 'warn',
  publicDir: false,
  build: {
    lib: { entry: 'src/sim/verify.js', formats: ['es'], fileName: () => 'sim.js' },
    outDir: OUT_DIR,
    emptyOutDir: false,
    minify: false,
    target: 'es2022',
    reportCompressedSize: false,
  },
});

const hash = simSourceHash();
const body = readFileSync(OUT, 'utf8');
writeFileSync(
  OUT,
  `// GENERATED by \`npm run build:sim\` from src/sim/verify.js. Do not edit.\n// sim-source-hash: ${hash}\n${body}`
);
console.log(`Wrote ${OUT} (${(body.length / 1024).toFixed(0)} KB, source hash ${hash})`);
