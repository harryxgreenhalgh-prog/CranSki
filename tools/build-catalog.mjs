// Writes the item catalogue, themed sets and Season Pass rewards from
// src/economy/catalog.js into a SQL migration, so the game and the database
// always agree on what exists and what it costs:  npm run build:catalog
import { writeFileSync } from 'node:fs';
import { SHOP_ITEMS, SETS, PASS_ITEMS, PASS_REWARDS } from '../src/economy/catalog.js';

export const CATALOG_FILE = 'supabase/migrations/20261116120100_catalog.sql';

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;

export function catalogSql() {
  const items = [...SHOP_ITEMS, ...SETS.flatMap((s) => s.items), ...PASS_ITEMS];
  const out = [
    '-- GENERATED by `npm run build:catalog` from src/economy/catalog.js. Do not edit.',
    '-- The item catalogue, limited-time sets and Season Pass rewards. Safe to run again.',
    '',
    'insert into public.item_sets (id, name, set_group, price, blurb) values',
    SETS.map((s) => `  (${[s.id, s.name, s.group, s.price, s.blurb].map(q).join(', ')})`).join(',\n'),
    'on conflict (id) do update set name = excluded.name, set_group = excluded.set_group, price = excluded.price, blurb = excluded.blurb;',
    '',
    'insert into public.items (id, name, kind, slot, rarity, source, price, set_id, look) values',
    items.map((it) => `  (${[it.id, it.name, it.kind, it.slot, it.rarity, it.source, it.source === 'shop' ? it.price : null, it.set || null].map(q).join(', ')}, ${json(it.look)})`).join(',\n'),
    'on conflict (id) do update set name = excluded.name, kind = excluded.kind, slot = excluded.slot, rarity = excluded.rarity,',
    '  source = excluded.source, price = excluded.price, set_id = excluded.set_id, look = excluded.look;',
    '',
    'insert into public.pass_rewards (level, track, item_id, frost) values',
    PASS_REWARDS.map((r) => `  (${[r.level, r.track, r.item || null, r.frost || null].map(q).join(', ')})`).join(',\n'),
    'on conflict (level, track) do update set item_id = excluded.item_id, frost = excluded.frost;',
    '',
  ];
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(CATALOG_FILE, catalogSql());
  console.log(`Wrote ${CATALOG_FILE}`);
}
