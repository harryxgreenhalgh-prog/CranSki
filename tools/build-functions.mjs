// Copies shared game code that Edge Functions need into their folders:
//   src/online/chatFilter.js -> supabase/functions/chat/filter.js
// (The simulation for submit-run is bundled by build-sim.mjs.)
//   npm run build:functions
import { readFileSync, writeFileSync } from 'node:fs';

export const COPIES = [['src/online/chatFilter.js', 'supabase/functions/chat/filter.js']];

export function copied(src) {
  return `// GENERATED by \`npm run build:functions\` from ${src}. Do not edit.\n${readFileSync(src, 'utf8')}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const [src, dst] of COPIES) {
    writeFileSync(dst, copied(src));
    console.log(`Wrote ${dst}`);
  }
}
