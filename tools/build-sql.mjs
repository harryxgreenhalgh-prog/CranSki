// Joins every file in supabase/migrations into supabase/setup.sql, so the
// whole database can be set up with one paste into the SQL Editor:
//   npm run build:sql
// Every migration is safe to run again, so setup.sql is too.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

export function combinedSql(root = '.') {
  const dir = `${root}/supabase/migrations`;
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  const head = `-- CranSki: the whole database in one file (GENERATED by \`npm run build:sql\`
-- from supabase/migrations; edit those files, not this one).
--
-- Paste all of this into the Supabase dashboard's SQL Editor and click Run.
-- It is safe to run again: anything already set up is left as it is or updated.
`;
  return head + files.map((f) => `\n-- =================================================================== ${f}\n\n${readFileSync(`${dir}/${f}`, 'utf8').trim()}\n`).join('');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('supabase/setup.sql', combinedSql());
  console.log('Wrote supabase/setup.sql');
}
